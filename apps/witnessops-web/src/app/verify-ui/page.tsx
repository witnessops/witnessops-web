function readReport(): HomepageHeroUiProofReport {
  const filePath = path.join(
    process.cwd(),
    "public",
    "ui-proofs",
    "homepage-hero",
    "latest.json",
  );
  return JSON.parse(readFileSync(filePath, "utf8")) as HomepageHeroUiProofReport;
}

function readPublicPngDimensions(publicPath: string) {
  const normalizedPath = publicPath.replace(/^\/+/, "");
  const filePath = path.join(process.cwd(), "public", normalizedPath);
  const buffer = readFileSync(filePath);
  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
  };
}

function summarizeScenarios(scenarios: ScenarioResult[]) {
  return scenarios.reduce(
    (summary, scenario) => ({
      ...summary,
      [scenario.status]: summary[scenario.status] + 1,
    }),
    { pass: 0, warn: 0, fail: 0 } satisfies Record<ScenarioStatus, number>,
  );
}

function formatIso(value: string) {
  return new Date(value).toISOString();
}

function SummaryCard({ label, value }: { label: string; value: number }) {
  return (
    <div className="border border-surface-border bg-surface-bg p-5">
      <div className="text-xs font-semibold uppercase tracking-[0.16em] text-text-muted">
        {label}
      </div>
      <div className="mt-3 text-3xl font-semibold text-text-primary">{value}</div>
    </div>
  );
}

function BoundaryCard({ title, body }: { title: string; body: string }) {
  return (
    <div className="border border-surface-border bg-surface-card p-4">
      <h2 className="text-sm font-semibold uppercase tracking-[0.08em] text-text-primary">
        {title}
      </h2>
      <p className="mt-2 text-sm leading-relaxed text-text-muted">{body}</p>
    </div>
  );
}

function ReportFact({
  label,
  value,
  mono,
  emphasize,
}: {
  label: string;
  value: string;
  mono?: boolean;
  emphasize?: boolean;
}) {
  return (
    <div className="border border-surface-border bg-surface-card p-4">
      <dt className="text-xs font-semibold uppercase tracking-[0.14em] text-text-muted">
        {label}
      </dt>
      <dd
        className={`mt-2 break-all ${
          mono ? "font-mono text-xs" : "text-sm"
        } ${emphasize ? "font-semibold uppercase text-text-primary" : "text-text-primary"}`}
      >
        {value}
      </dd>
    </div>
  );
}

function StatusPill({ status }: { status: ScenarioStatus | ReportStatus }) {
  const label =
    status === "pass" ? "Pass" : status === "warn" ? "Warn" : "Fail";
  return (
    <span className="inline-flex border border-surface-border bg-surface-card px-2 py-1 text-xs font-semibold uppercase tracking-[0.12em] text-text-primary">
      {label}
    </span>
  );
}
