type ReportStatus = "pass" | "warn" | "fail";
type ScenarioStatus = "pass" | "warn" | "fail";
type ScenarioSeverity = "critical" | "warning";

type CheckResult = {
  name: string;
  status: "pass" | "fail";
  severity: ScenarioSeverity;
  expected?: string;
  actual?: string | number | boolean | null;
  message?: string;
};

type ScenarioResult = {
  scenario: {
    name: string;
    viewport: {
      width: number;
      height: number;
    };
    colorScheme: string;
    reducedMotion: string;
    contentVariant: string;
    deviceScaleFactor: number;
    assetMode?: string;
    severity: ScenarioSeverity;
  };
  status: ScenarioStatus;
  checks: CheckResult[];
  metrics: {
    cls?: number;
    ctaWidth?: number;
    ctaHeight?: number;
    scrollWidth?: number;
    clientWidth?: number;
    activeAnimationCount?: number;
  };
  screenshotPath: string | null;
};

type HomepageHeroUiProofReport = {
  schemaVersion: "ui-proof-report.v1";
  proofType: "witnessops.web.homepage-hero.mobile";
  status: ReportStatus;
  repo: "witnessops/witnessops-web";
  route: "/";
  generatedAt: string;
  commitSha: string;
  browser: "chromium";
  asset: {
    assetId: string;
    src: string;
    width: number;
    height: number;
    sourcePath?: string;
    sourceRecord?: string;
    sourceStatus?: string;
    sourceCommit?: string;
    sourceSha256?: string;
  };
  artifacts: {
    report: string;
    grid: string;
    screenshotsDir: string;
  };
  scenarios: ScenarioResult[];
};

