 const name='proofpack-pr_lsa_20260710120000_198fd7aceb.zip',path=resolve('tests/proofpack/production-fixtures/adverse',name);
 const checked=await verifyProofpack({proofpack:{name,bytes:readFileSync(path)},signature:{name:name+'.sig.json',bytes:readFileSync(path+'.sig.json')},trust_registry:pinnedRegistryInput()});
 const model=localAuditAdapter(checked,'2026-09-18T12:00:00Z')!;expect(model).toBeTruthy();
 const run:LinuxCheckRun={id:'linux-run',assetId:'linux-asset',createdAt:model.identity.generatedAt,sourceDigest:model.identity.sourceDigest,proofRunId:checked.proof_run_id,verifierVersion:checked.verifier_version,profileId:'linux_baseline_v1',outcome:checked.outcome,synthetic:true,observedHostname:model.subject.label,observedAt:model.subject.observedAt,sourceAssetId:'asset-demo-host-001',machineIdentity:null};
