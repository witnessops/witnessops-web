import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { RECOMMENDED_PROFILE, type Run, type Workspace } from '../../apps/witnessops-app/src/lib/model';
import { canonicalSource } from '../../apps/witnessops-app/src/lib/source-digest';
const source=JSON.parse(readFileSync(resolve('tests/external-exposure/fixtures/public-witnessops-snapshot-20260910.json'),'utf8'));
for(const width of [390,1440]) for(const role of ['owner','viewer'] as const) test(`finding-led actions ${role} ${width}`,async({page},info)=>{
 const snapshot=structuredClone(source),check=snapshot.checks.find((c:{check_id:string})=>c.check_id==='web.hsts.v1');
 check.status='NEEDS_ATTENTION';check.interpretation='Recorded fixture interpretation.';check.recommendation='Review the HTTPS response configuration.';
 const run:Run={id:'run-actions',assetId:'asset-actions',createdAt:snapshot.finished_at,profile:structuredClone(RECOMMENDED_PROFILE),snapshot,sourceDigest:createHash('sha256').update(canonicalSource(snapshot)).digest('hex')};
 const ws:Workspace={id:'workspace-actions',name:'Private workspace',slug:'actions',role,members:[],assets:[{id:run.assetId,hostname:snapshot.target,type:'hostname',createdAt:run.createdAt}],runs:[run]};
 const writes:string[]=[];
 await page.setViewportSize({width,height:900});
 await page.route('**/api/**',route=>{const path=new URL(route.request().url()).pathname;
 if(path==='/api/workspace')return route.fulfill({json:{user:{id:'user'},workspaces:[ws],workspace:ws}});
 if(path==='/api/events')return route.fulfill({json:{recorded:true}});
 if(path==='/api/feedback')return route.fulfill({json:[]});
 writes.push(path);return route.abort();});
 await page.goto(`/reports/${run.id}`);
 const article=page.getByRole('article',{name:'Snapshot results'});
 await expect(article).toBeVisible();
 await expect(page.getByRole('region',{name:'Visual report overview'})).toHaveCount(0);
 await expect(article).toContainText(check.recommendation);
 await expect(article).toContainText('Run record — integrity hash (SHA-256), not yet signed.');
 await expect(article).toContainText(run.sourceDigest);
 await expect(article.getByRole('button',{name:'Ask about this finding'})).toHaveCount(0);
 const open=article.getByRole('link',{name:'Open the recorded check'}).first();
 await expect(open).toHaveAttribute('href',`/runs/${run.id}/observations/${check.check_id}`);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:info.outputPath(`report-short-${role}-${width}.png`)});
 await page.emulateMedia({media:'print'});
 const print=page.locator('[data-run-record-print]');
 await expect(print).toContainText(check.recommendation);
 await expect(print.getByRole('button')).toHaveCount(0);
 await page.emulateMedia({media:'screen'});
 await open.click();
 await expect(page).toHaveURL(new RegExp(`/observations/${check.check_id}$`));
 expect(writes).toEqual([]);
});

